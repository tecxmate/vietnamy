const TRANS = {
    en,
    'zh-s': zhS,
    'zh-t': zhT,
};

export function normalizeLang(lang) {
    if (!lang) return DEFAULT_APP_LANG;
    if (lang === 'zh') return 'zh-s';
    if (lang === 'zh-s' || lang === 'zh-t' || lang === 'en') return lang;
    return DEFAULT_APP_LANG;
};

export function getT(lang) {
    const normalized = normalizeLang(lang);
    const dict = TRANS[normalized] || en;
    return (key, fallback) => dict[key] ?? en[key] ?? fallback ?? key;
}

export function useT() {
    const { userProfile } = useUser();
    return getT(userProfile?.nativeLang);
}
