#!/usr/bin/env node
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import Database from 'better-sqlite3';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT_DIR = path.resolve(__dirname, '..');
const DEFAULT_DB = path.join(ROOT_DIR, 'server', 'databases', 'app_ops.db');

const args = new Map();
for (let i = 2; i < process.argv.length; i += 1) {
  const arg = process.argv[i];
  if (arg.startsWith('--')) {
    const [key, inlineValue] = arg.slice(2).split('=', 2);
    const value = inlineValue ?? process.argv[i + 1];
    args.set(key, value);
    if (inlineValue == null && value && !value.startsWith('--')) i += 1;
  }
}

const dbPath = path.resolve(args.get('db') || process.env.APP_OPS_DB_PATH || DEFAULT_DB);
const outPath = args.get('out') ? path.resolve(args.get('out')) : '';

if (!fs.existsSync(dbPath)) {
  console.error(`App ops DB not found: ${dbPath}`);
  process.exit(1);
}

const db = new Database(dbPath, { readonly: true });

function sql(value) {
  if (value == null) return 'NULL';
  return `'${String(value).replace(/'/g, "''")}'`;
}

function bool(value) {
  return value ? 'true' : 'false';
}

function jsonb(value, fallback) {
  const raw = value == null || value === '' ? fallback : value;
  try {
    JSON.parse(raw);
    return `${sql(raw)}::jsonb`;
  } catch {
    return `${sql(fallback)}::jsonb`;
  }
}

function insert(table, columns, rows, conflictTarget) {
  if (!rows.length) return '';
  const lines = rows.map(row => {
    const values = columns.map(col => row[col.sql] ?? 'NULL').join(', ');
    return `(${values})`;
  });
  return [
    `INSERT INTO public.${table} (${columns.map(col => col.pg).join(', ')}) VALUES`,
    lines.join(',\n'),
    `ON CONFLICT (${conflictTarget}) DO NOTHING;`,
    '',
  ].join('\n');
}

function rows(query) {
  try {
    return db.prepare(query).all();
  } catch {
    return [];
  }
}

