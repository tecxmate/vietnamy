#!/usr/bin/env node
// Export app-owned Supabase Postgres tables as portable INSERT SQL for Neon.
//
// Usage:
//   node scripts/export-supabase-neon-sql.mjs --out=backups/supabase-neon.sql
//   node scripts/export-supabase-neon-sql.mjs --tables=profiles,user_progress
//   node scripts/export-supabase-neon-sql.mjs --limit=100
//
// Required env:
//   SUPABASE_URL or VITE_SUPABASE_URL
//   SUPABASE_SERVICE_ROLE_KEY

import { createClient } from '@supabase/supabase-js';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'fs';
import { dirname, join, resolve } from 'path';
import { fileURLToPath } from 'url';
import { selectMigrationTables } from './backend-migration-tables.mjs';

const ROOT = join(fileURLToPath(new URL('.', import.meta.url)), '..');

function loadEnvFile(path) {
    if (!existsSync(path)) return;
    for (const line of readFileSync(path, 'utf8').split(/\r?\n/)) {
        const trimmed = line.trim();
        if (!trimmed || trimmed.startsWith('#')) continue;
        const match = trimmed.match(/^([A-Za-z_][A-Za-z0-9_]*)=(.*)$/);
        if (!match) continue;
        const [, key, rawValue] = match;
        if (process.env[key] !== undefined) continue;
        process.env[key] = rawValue.replace(/^['"]|['"]$/g, '');
    }
}

loadEnvFile(join(ROOT, '.env.local'));
loadEnvFile(join(ROOT, '.env'));

const args = Object.fromEntries(process.argv.slice(2).map(arg => {
    const match = arg.match(/^--([^=]+)(?:=(.*))?$/);
    return match ? [match[1], match[2] ?? 'true'] : [arg, 'true'];
}));

const SUPABASE_URL = (process.env.SUPABASE_URL || process.env.VITE_SUPABASE_URL || '').replace(/\/+$/, '');
const SERVICE_ROLE = process.env.SUPABASE_SERVICE_ROLE_KEY || '';
const PAGE_SIZE = Math.min(Math.max(Number.parseInt(args['page-size'], 10) || 1000, 1), 1000);
const LIMIT = args.limit ? Math.max(Number.parseInt(args.limit, 10) || 0, 0) : 0;
const tables = selectMigrationTables(args.tables || '');
const outPath = args.out && args.out !== 'true' ? resolve(args.out) : '';

function requireEnv(name, value) {
    if (!value) {
        console.error(`Missing ${name}. Fill it in .env/.env.local or export it before running.`);
        process.exit(1);
    }
}

requireEnv('SUPABASE_URL', SUPABASE_URL);
requireEnv('SUPABASE_SERVICE_ROLE_KEY', SERVICE_ROLE);

if (!tables.length) {
    console.error('No matching tables selected.');
    process.exit(1);
}

const supabase = createClient(SUPABASE_URL, SERVICE_ROLE, {
    auth: { persistSession: false, autoRefreshToken: false },
});

function ident(value) {
    return `"${String(value).replace(/"/g, '""')}"`;
}

function literal(value, { jsonb = false, column = '' } = {}) {
    if (jsonb) {
        const fallback = column === 'client_logs' ? [] : {};
        return `'${JSON.stringify(value ?? fallback).replace(/'/g, "''")}'::jsonb`;
    }
    if (value === null || value === undefined) return 'NULL';
    if (typeof value === 'boolean') return value ? 'true' : 'false';
    if (typeof value === 'number' && Number.isFinite(value)) return String(value);
    return `'${String(value).replace(/'/g, "''")}'`;
}

async function fetchRows(table) {
    const rows = [];
    for (let from = 0; ; from += PAGE_SIZE) {
        const to = from + PAGE_SIZE - 1;
        let query = supabase
            .from(table.name)
            .select(table.columns.join(','))
            .range(from, to);
        if (table.orderBy) query = query.order(table.orderBy, { ascending: true });
        const { data, error } = await query;
        if (error) throw new Error(`${table.name}: ${error.message}`);
        rows.push(...(data || []));
        if ((data || []).length < PAGE_SIZE || (LIMIT && rows.length >= LIMIT)) break;
    }
    return LIMIT ? rows.slice(0, LIMIT) : rows;
}

function insertSql(table, rows) {
    if (!rows.length) return `-- ${table.name}: 0 rows\n`;
    const jsonbColumns = new Set(table.jsonb);
    const values = rows.map(row => `(${table.columns.map(column => literal(row[column], { jsonb: jsonbColumns.has(column), column })).join(', ')})`);
    const conflict = table.primaryKey.map(ident).join(', ');
    const updateColumns = table.columns.filter(column => !table.primaryKey.includes(column));
    const updateSql = updateColumns.length
        ? `DO UPDATE SET ${updateColumns.map(column => `${ident(column)} = excluded.${ident(column)}`).join(', ')}`
        : 'DO NOTHING';
    return [
        `-- ${table.name}: ${rows.length} rows`,
        `INSERT INTO public.${ident(table.name)} (${table.columns.map(ident).join(', ')}) VALUES`,
        values.join(',\n'),
        `ON CONFLICT (${conflict}) ${updateSql};`,
        '',
    ].join('\n');
}

const output = [];
output.push('-- Generated by scripts/export-supabase-neon-sql.mjs');
output.push(`-- Source: ${SUPABASE_URL}`);
output.push(`-- Generated at: ${new Date().toISOString()}`);
output.push('-- Run after neon/migrations/202606110001_backend_foundation.sql');
output.push('BEGIN;');
output.push('');

for (const table of tables) {
    console.error(`Exporting ${table.name}...`);
    const rows = await fetchRows(table);
    output.push(insertSql(table, rows));
}

output.push('COMMIT;');
output.push('');

const text = output.filter(Boolean).join('\n');
if (outPath) {
    mkdirSync(dirname(outPath), { recursive: true });
    writeFileSync(outPath, text);
    console.log(`Wrote ${outPath}`);
} else {
    process.stdout.write(text);
}
